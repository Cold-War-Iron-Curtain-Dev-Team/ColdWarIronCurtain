"""Generate Congress lobbying tooltips and state-dependent feedback text."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCALISATION = ROOT / "localisation/english/US_Congress_Lobbying_l_english.yml"
SCRIPTED_LOC = ROOT / "common/scripted_localisation/USA_congress_lobbying_localisation.txt"
FACTIONS = [
    (1, "MOD_DEM", "Moderate Democrats", "moderate_dem", "senate_mod_lobbying", "SENATE_FACTION_EST_DEM"),
    (2, "PRO_DEM", "Progressive Democrats", "progressive_dem", "senate_pro_lobbying", "SENATE_FACTION_PRO_DEM"),
    (3, "DIXIE_DEM", "Dixiecrat Democrats", "dixiecrat_dem", "senate_dixie_lobbying", "SENATE_FACTION_DIXIE_DEM"),
    (4, "MOD_GOP", "Moderate Republicans", "moderate_gop", "senate_mod_gop_lobbying", "SENATE_FACTION_EST_GOP"),
    (5, "CON_GOP", "Conservative Republicans", "conservative_gop", "senate_con_gop_lobbying", "SENATE_FACTION_CON_GOP"),
    (6, "LIB_GOP", "Liberal Republicans", "liberal_gop", "senate_lib_gop_lobbying", "SENATE_FACTION_LIB_GOP"),
]


def text_function(name, entries):
    lines = ["defined_text = {", f"\tname = {name}"]
    for trigger, key in entries:
        lines.append("\ttext = {")
        if trigger:
            lines.append(f"\t\ttrigger = {{ {trigger} }}")
        lines.extend([f"\t\tlocalization_key = {key}", "\t}"])
    return "\n".join(lines + ["}", ""])



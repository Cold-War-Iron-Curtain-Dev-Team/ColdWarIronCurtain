"""Generate Congress colour definitions from the shared state silhouettes.

Edit PARTY_COLOURS to change the map colours; no DDS recolouring is needed.
Run with --check to verify that the generated definitions are current.
"""

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MASK_DIRECTORY = ROOT / "gfx/Scripted_GUI_Special/USA/Democratic_States"
OUTPUT = ROOT / "interface/US_Congress_State_Overlays.gfx"
PARTY_COLOURS = {
    "DEM": (66, 100, 170),
    "GOP": (140, 69, 66),
    "SPLIT": (123, 69, 140),
    "AIP": (198, 125, 66),
}
OVERLAY_COLOURS = {**PARTY_COLOURS, "NEUTRAL": (165, 174, 185)}
OPACITY = 0.5


def shader_path(party):
    return ROOT / f"gfx/FX/usa_congress_{party.lower()}_overlay.shader"


def generate_shader(party):
    """Use the native sprite vertex/constant layout, not the progress-bar layout."""
    rgba = ", ".join(f"{channel / 255:.6f}" for channel in OVERLAY_COLOURS[party])
    return '''# Generated by _tools/generate_us_congress_overlays.py.
Includes = {
    "buttonstate.fxh"
}

PixelShader = {
    Samplers = {
        MapTexture = {
            Index = 0
            MagFilter = "Point"
            MinFilter = "Point"
            MipFilter = "None"
            AddressU = "Clamp"
            AddressV = "Clamp"
        }
    }
}

VertexStruct VS_OUTPUT {
    float4 vPosition : PDX_POSITION;
    float2 vTexCoord : TEXCOORD0;
};

VertexShader = {
    MainCode VertexShader
    [[
        VS_OUTPUT main(const VS_INPUT v)
        {
            VS_OUTPUT Out;
            Out.vPosition = mul(WorldViewProjectionMatrix, float4(v.vPosition.xyz, 1));
            Out.vTexCoord = v.vTexCoord + Offset;
            return Out;
        }
    ]]
}

PixelShader = {
    MainCode StateOverlay
    [[
        float4 main(VS_OUTPUT v) : PDX_COLOR
        {
            float maskAlpha = tex2D(MapTexture, v.vTexCoord).a;
            return float4(TINT_RGB, maskAlpha * TINT_ALPHA) * Color;
        }
    ]]
}

BlendState BlendState {
    BlendEnable = yes
    SourceBlend = "SRC_ALPHA"
    DestBlend = "INV_SRC_ALPHA"
}
'''.replace("TINT_RGB", rgba).replace("TINT_ALPHA", str(OPACITY)) + "\n".join(
        f'''\nEffect {state} {{
    VertexShader = "VertexShader"
    PixelShader = "StateOverlay"
}}''' for state in ("Up", "Down", "Over", "Disable")
    ) + "\n"


def generate():
    # DC and Puerto Rico have neutral fills, but no voting Senate delegations.
    masks = sorted(
        path for path in MASK_DIRECTORY.iterdir()
        if path.suffix.lower() == ".dds"
    )
    assert len(masks) == 52, f"Expected 52 map masks, found {len(masks)}"
    lines = [
        "# Generated by _tools/generate_us_congress_overlays.py.",
        "# Party and neutral colours reuse the same masks as the election maps.",
        "spriteTypes = {",
    ]
    for party in OVERLAY_COLOURS:
        for mask in masks:
            if party != "NEUTRAL" and mask.stem in {"GOP_DC", "GOP_PR"}:
                continue
            texture = mask.relative_to(ROOT).as_posix()
            state = mask.stem.removeprefix("GOP_")
            lines.extend([
                "\tspriteType = {",
                f'\t\tname = "GFX_{party}_{state}"',
                f'\t\ttexturefile = "{texture}"',
                '\t\tnoOfFrames = 1',
                # These decorative overlays do not need CPU alpha hit testing.
                # Enabling it rejects the existing DXT5 mask compression.
                '\t\ttransparencecheck = no',
                f'\t\teffectFile = "{shader_path(party).relative_to(ROOT).as_posix()}"',
                "\t}",
            ])
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate()
    if args.check:
        assert OUTPUT.read_text(encoding="utf-8") == result, "Regenerate Congress overlays."
        for party in OVERLAY_COLOURS:
            assert shader_path(party).read_text(encoding="utf-8") == generate_shader(party)
        print("PASS: all 252 colour definitions use the shared masks.")
    else:
        OUTPUT.write_text(result, encoding="utf-8", newline="\n")
        for party in OVERLAY_COLOURS:
            shader_path(party).write_text(generate_shader(party), encoding="utf-8", newline="\n")
        print(f"Generated {OUTPUT.name}: 252 colour definitions, 52 shared masks.")


if __name__ == "__main__":
    main()

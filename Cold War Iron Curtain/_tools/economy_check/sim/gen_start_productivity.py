#!/usr/bin/env python3
"""Writes the simulator's fitted per-country start factor (MODEL.md 0.1) into the mod as a scripted effect.

  python _tools/economy_check/sim/gen_start_productivity.py
"""
import csv, os

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
SRC = os.path.join(HERE, 'out', 'start_productivity.csv')
DST = os.path.join(MOD, 'common', 'scripted_effects', 'CWIC_Start_Productivity_Generated.txt')

rows = sorted(csv.DictReader(open(SRC)), key=lambda r: r['tag'])
out = ['# Generated by _tools/economy_check/sim/gen_start_productivity.py from the simulator fit. Do not edit by hand.',
       'cwic_set_start_productivity = {',
       '\tset_variable = { cwic_start_productivity = 1 }']
for r in rows:
    out.append('\tif = { limit = { original_tag = %s } set_variable = { cwic_start_productivity = %.4f } }'
               % (r['tag'], float(r['cwic_start_productivity'])))
out.append('}')
open(DST, 'w', newline='\n').write('\n'.join(out) + '\n')
print('%d countries -> %s' % (len(rows), os.path.relpath(DST, MOD)))

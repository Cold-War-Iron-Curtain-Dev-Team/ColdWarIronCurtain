"""Build the shared WW3 occupation predicates, participant tracking and UI status."""
import argparse
import json

from ww3_script import ROOT, parse, one, write


def build():
    manifest = json.loads((ROOT/'_tools/ww3/objectives.json').read_text())
    groups = manifest['groups']
    states, province_state = {}, {}
    for path in (ROOT/'history/states').glob('*.txt'):
        state = one(parse(path.read_text(encoding='utf-8-sig')), 'state')
        sid = int(one(state, 'id'))
        provinces = [int(p) for p in one(state, 'provinces') if isinstance(p, str) and p.isdigit()]
        states[sid] = provinces
        for p in provinces:
            assert p not in province_state
            province_state[p] = sid
    ids = [sid for g in groups for sid in g['states']]
    assert len(ids) == len(set(ids)), 'A state must belong to one objective theatre'
    assert all(g['states'] for g in groups)
    for g in groups:
        assert province_state[g['capital_province']] in g['states'], ('Capital outside theatre', g['tag'])
    header = '# GENERATED by _tools/ww3/build_ww3_objectives.py; edit objectives.json instead.\n\n'
    triggers = header
    loc = 'l_english:\n'
    effects = header + 'cwic_ww3_refresh_objectives = {\n'
    effects += '    # Opponent flags survive capitulation, exile and scripted successor governments.\n'
    effects += '''    every_enemy_country = {
        limit = { NOT = { cwic_ww3_soviet_aligned = yes } }
        set_country_flag = cwic_ww3_opponent
    }
    set_variable = { cwic_ww3_required_count = 0 }
    set_variable = { cwic_ww3_objectives_total = 0 }
    set_variable = { cwic_ww3_objectives_held = 0 }
'''
    scripted_loc = header
    labels = []
    for g in groups:
        tag, label = g['tag'], g['label']
        flag = 'cwic_ww3_required_' + tag
        trigger = 'cwic_ww3_' + tag + '_secured'
        # Reconstruct already conquered theatres when loading a legacy save, without
        # requiring neutral states to become enemies or recreating their old tags.
        conditions = []
        for alias in g['aliases']:
            conditions.append(f'            {alias} = {{ has_country_flag = cwic_ww3_opponent }}')
        conditions.append(f'            {trigger} = yes')
        if tag == 'AUS':
            conditions.append('            ADR = { cwic_ww3_soviet_aligned = yes exists = yes }')
        effects += f'''    if = {{
        limit = {{ OR = {{
{chr(10).join(conditions)}
        }} }}
        set_country_flag = {flag}
    }}
    if = {{
        limit = {{ has_country_flag = {flag} }}
        add_to_variable = {{ cwic_ww3_required_count = 1 }}
        add_to_variable = {{ cwic_ww3_objectives_total = {len(g['states'])} }}
'''
        for sid in g['states']:
            effects += f'        if = {{ limit = {{ {sid} = {{ cwic_ww3_state_{sid}_secured = yes }} }} add_to_variable = {{ cwic_ww3_objectives_held = 1 }} }}\n'
        effects += '    }\n'
        triggers += trigger + ' = {\n'
        for sid in g['states']:
            triggers += f'    {sid} = {{ cwic_ww3_state_{sid}_secured = yes }}\n'
        triggers += '}\n\n'
        triggers += f'''cwic_ww3_capital_{tag}_secured = {{
    custom_trigger_tooltip = {{
        tooltip = CWIC_WW3_CAPITAL_{tag}_TT
        SOV = {{
            OR = {{
                controls_province = {g['capital_province']}
                any_country = {{ cwic_ww3_soviet_aligned = yes controls_province = {g['capital_province']} }}
            }}
        }}
    }}
}}

'''
        loc += f' CWIC_WW3_CAPITAL_{tag}_TT: "The Soviet bloc controls the fixed {label} capital objective. Moving the government does not move this objective."\n'
        loc += f' CWIC_WW3_{tag}_HEADER_TT: "§Y{label}§!: all required states are secured."\n'
        loc += f' CWIC_WW3_{tag}_DONE: "§G{label}: secured§!"\n'
        loc += f' CWIC_WW3_{tag}_PENDING: "§R{label}: objectives remain§!"\n'
        loc += f' CWIC_WW3_{tag}_NEUTRAL: "§g{label}: not required§!"\n'
        name = 'GetCwicWW3' + tag + 'Status'
        labels.append('[' + name + ']')
        scripted_loc += f'''defined_text = {{
    name = {name}
    text = {{ trigger = {{ NOT = {{ SOV = {{ has_country_flag = {flag} }} }} }} localization_key = CWIC_WW3_{tag}_NEUTRAL }}
    text = {{ trigger = {{ {trigger} = yes }} localization_key = CWIC_WW3_{tag}_DONE }}
    text = {{ localization_key = CWIC_WW3_{tag}_PENDING }}
}}

'''
    effects += '}\n'
    effects += '\ncwic_ww3_reset_objectives = {\n'
    for g in groups:
        effects += f"    clr_country_flag = cwic_ww3_required_{g['tag']}\n"
    effects += '''    every_country = {
        clr_country_flag = cwic_ww3_opponent
        clr_country_flag = cwic_ww3_deadline_adjusted
    }
}
'''
    # Fast path: one aligned controller holds the whole state. The fallback handles
    # mixed Soviet/allied occupation, checking EVERY province rather than trusting
    # the majority state controller or a cached province_controllers array.
    for sid in sorted(ids):
        loc += f' CWIC_WW3_STATE_{sid}_TT: "All provinces in §Y$STATE_{sid}$§! are controlled by the Soviet Union, its allies, subjects or Soviet-aligned successor governments."\n'
        triggers += f'''cwic_ww3_state_{sid}_secured = {{
    custom_trigger_tooltip = {{
        tooltip = CWIC_WW3_STATE_{sid}_TT
        OR = {{
            controller = {{
                cwic_ww3_soviet_aligned = yes
                PREV = {{ is_fully_controlled_by = PREV }}
            }}
            SOV = {{
'''
        for p in states[sid]:
            triggers += f'                    OR = {{ controls_province = {p} any_country = {{ cwic_ww3_soviet_aligned = yes controls_province = {p} }} }}\n'
        triggers += '            }\n        }\n    }\n}\n\n'
    triggers += '''cwic_ww3_europe_secured = {
    custom_trigger_tooltip = {
        tooltip = CWIC_WW3_OBJECTIVES_REGISTERED_TT
        check_variable = { cwic_ww3_required_count > 0 }
    }
'''
    for g in groups:
        tag = g['tag']
        triggers += f'''    if = {{
        limit = {{ has_country_flag = cwic_ww3_required_{tag} }}
        custom_trigger_tooltip = {{ tooltip = CWIC_WW3_{tag}_HEADER_TT cwic_ww3_{tag}_secured = yes }}
'''
        for sid in g['states']:
            triggers += f'        {sid} = {{ cwic_ww3_state_{sid}_secured = yes }}\n'
        triggers += '    }\n'
    triggers += '}\n'
    # Fixed capital reporting retained for old UI consumers, with total red fallback.
    old_capitals = [('paris','FRA',11506,'Paris'), ('helsinki','FIN',11105,'Helsinki'),
                    ('stockholm','SWE',6050,'Stockholm'), ('oslo','NOR',6115,'Oslo'),
                    ('west_berlin','WGR',6521,'West Berlin'), ('rome','ITA',9904,'Rome'),
                    ('vienna','AUS',13297,'West Vienna'), ('athens','GRE',4109,'Athens'),
                    ('madrid','SPR',9767,'Madrid'), ('lisbon','POR',11805,'Lisbon')]
    old_loc = header
    for key, tag, p, city in old_capitals:
        old_loc += f'''defined_text = {{
    name = get_{key}_capital
    text = {{
        trigger = {{ SOV = {{ OR = {{ controls_province = {p} any_country = {{ cwic_ww3_soviet_aligned = yes controls_province = {p} }} }} }} }}
        localization_key = {key}_capital_green
    }}
    text = {{ localization_key = {key}_capital_red }}
}}

'''
    outputs = {
        'common/scripted_triggers/CWIC_WW3_Objectives_triggers.txt': triggers,
        'common/scripted_effects/CWIC_WW3_Objectives_effects.txt': effects,
        'common/scripted_localisation/CWIC_WW3_Objectives_loc.txt': scripted_loc,
        'common/scripted_localisation/IC_SOV_WW3.txt': old_loc,
        'localisation/english/CWIC_WW3_Objectives_l_english.yml': loc,
    }
    return {name: text.rstrip() + '\n' for name, text in outputs.items()}, labels


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    outputs, _ = build()
    changed = []
    for name, text in outputs.items():
        path = ROOT/name
        if not path.exists() or path.read_text(encoding='utf-8-sig') != text:
            changed.append(name)
            if not args.check:
                write(name, text, bom=name.endswith('.yml'))
    print(('Out of date: ' if args.check else 'Updated: ') + str(len(changed)) + ' generated files')
    if args.check and changed:
        raise SystemExit('\n'.join(changed))


if __name__ == '__main__':
    main()

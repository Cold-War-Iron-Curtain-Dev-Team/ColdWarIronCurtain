# ============================================================ scripted localisation
def defined(name, branches, default="SOV_pres_empty"):
    b = "".join(f"\ttext = {{ trigger = {{ {trig} }} localization_key = {key} }}\n" for trig, key in branches)
    return f"defined_text = {{\n\tname = {name}\n{b}\ttext = {{ localization_key = {default} }}\n}}\n"



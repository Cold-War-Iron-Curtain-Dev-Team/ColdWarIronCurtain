    SL.append(defined(f"SOV_pres_s{i}_name", char_br(f"SOV_pres_seat_char^{i - 1}", "_ranked_ui"), "SOV_pres_vacant"))
    SL.append(defined(f"SOV_pres_s{i}_title", min_br(f"SOV_pres_seat_min^{i - 1}")))
    SL.append(defined(f"SOV_pres_s{i}_faction", char_br(f"SOV_pres_seat_char^{i - 1}", "_faction_ui")))

"""Generates every Soviet Presidium inlay file from presidium_data.py.

Run:  python gen_presidium.py
Writes into the mod folder two levels up (this file lives in <mod>/_tools/presidium/).
Set MOD_ROOT to override.
"""
import os, re, struct, zlib
from pathlib import Path
from presidium_data import *

MOD = Path(os.environ.get("MOD_ROOT") or Path(__file__).resolve().parents[2])
HDR = "# GENERATED by _tools/presidium/gen_presidium.py - edit presidium_data.py instead\n"
BLANK = "GFX_SOV_pres_blank"

CID = {c["key"]: i + 1 for i, c in enumerate(CHARACTERS)}
FID = {f[0]: i + 1 for i, f in enumerate(FACTIONS)}
MID = {m[0]: i + 1 for i, m in enumerate(MINISTRIES)}
MIN = {m[0]: m for m in MINISTRIES}
CH = {c["key"]: c for c in CHARACTERS}
SLOTS = range(1, MAX_SEATS + 1)

# ---- validation
for c in CHARACTERS:
    assert c["faction"] in FID, f"{c['key']}: unknown faction {c['faction']}"
    for t in c["traits"]:
        assert t in TRAITS, f"{c['key']}: unknown trait {t}"
for m, h in START_SEATS:
    assert m in MID and (h is None or h in CID), f"START_SEATS: bad entry {m}, {h}"
assert len(START_SEATS) <= MAX_SEATS and LAYOUT_BREAKS[-1] == MAX_SEATS


def write(rel, data, bom=False):
    p = MOD / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(data, bytes):
        p.write_bytes(data)
    else:
        p.write_text(data, encoding="utf-8-sig" if bom else "utf-8")
    print("wrote", rel)


def cv(var, val):
    return f"check_variable = {{ {var} = {val} }}"


# ============================================================ layouts
W, LEFT_W, TOP, GRID_H, TEXT_H = 1000, 175, 45, 560, 54
GRID_W = W - LEFT_W - 5


def best_layout(n):
    best = None
    for cols in range(2, 8):
        rows = -(-n // cols)
        cell_w = GRID_W // cols
        s = min(0.65, (GRID_H / rows - TEXT_H - 6) / 210, (cell_w - 10) / 156)
        if cell_w >= 130 and (best is None or s > best[2]):
            best = (cols, rows, s, cell_w)
    return best


LAYOUTS = []  # (index, lo, hi, cols, rows, scale, cell_w)
lo = 0
for i, hi in enumerate(LAYOUT_BREAKS, 1):
    cols, rows, s, cw = best_layout(hi)
    LAYOUTS.append((i, lo, hi, cols, rows, s, cw))
    lo = hi
H = max(TOP + L[4] * (int(210 * L[5]) + TEXT_H + 6) for L in LAYOUTS) + 10


def slot_shown(L, i):
    lo, hi = L[1], L[2]
    return f"check_variable = {{ SOV_pres_seat_min^num > {max(lo, i - 1)} }} check_variable = {{ SOV_pres_seat_min^num < {hi + 1} }}"


# ============================================================ blank sprite (8x8 transparent tga)
write("gfx/interface/SOV_pres_blank.tga",
      struct.pack("<BBBHHBHHHHBB", 0, 0, 2, 0, 0, 0, 0, 0, 8, 8, 32, 8) + bytes(8 * 8 * 4))
write("interface/SOV_Stalin_presidium.gfx", HDR + f"""spriteTypes = {{
	spriteType = {{
		name = "{BLANK}"
		texturefile = "gfx/interface/SOV_pres_blank.tga"
	}}
}}
""")

# ============================================================ .gui
def text(name, x, y, w, ctx, font="hoi_16mbs"):
    return f"""		instantTextBoxType = {{
			name = "{name}"
			position = {{ x = {x} y = {y} }}
			font = "{font}"
			context_aware_text = {ctx}
			maxWidth = {w}
			maxHeight = 18
			fixedsize = yes
			format = center
			alwaystransparent = yes
		}}
"""


def icon(name, x, y, sc, tt):
    return f"""		iconType = {{
			name = "{name}"
			spriteType = "{BLANK}"
			position = {{ x = {x} y = {y} }}
			scale = {sc:.2f}
			context_aware_tooltip = {tt}
		}}
"""


gui = [HDR, f"""guiTypes = {{
	containerWindowType = {{
		name = "SOV_presidium_inlay_window"
		position = {{ x = 0 y = 0 }}
		size = {{ width = {W} height = {H} }}
		clipping = no
		background = {{ name = "background" quadTextureSprite = "GFX_tiled_window_transparent" }}
"""]
gui.append(text("SOV_pres_title", 0, 10, W, "[SOV_pres_title_text]", "hoi_20bs"))
gui.append(icon("SOV_pres_leader_portrait", 33, 60, 0.7, "[SOV_pres_leader_tt]"))
gui.append(text("SOV_pres_leader_name", 0, 212, LEFT_W, "[SOV_pres_leader_name]", "hoi_18mbs"))
gui.append(text("SOV_pres_leader_title", 0, 232, LEFT_W, "[SOV_pres_leader_title]"))
for L in LAYOUTS:
    li, _, hi, cols, rows, s, cw = L
    row_h = int(210 * s) + TEXT_H + 6
    for i in range(1, hi + 1):
        cx, cy = LEFT_W + ((i - 1) % cols) * cw, TOP + ((i - 1) // cols) * row_h
        py = cy + int(210 * s) + 2
        n = f"SOV_pres_L{li}_s{i}"
        gui.append(icon(f"{n}_portrait", cx + (cw - int(156 * s)) // 2, cy, s, f"[{n}_tt]"))
        gui.append(text(f"{n}_name", cx, py, cw - 4, f"[{n}_name]"))
        gui.append(text(f"{n}_title", cx, py + 16, cw - 4, f"[{n}_title]"))
        gui.append(text(f"{n}_faction", cx, py + 32, cw - 4, f"[{n}_faction]"))
gui.append("\t}\n}\n")
write("interface/SOV_Stalin_presidium_inlay.gui", "".join(gui))

# ============================================================ inlay window
def portrait_list(var):
    return "".join(f"\t\t\t{CH[c]['portrait']} = {{ {cv(var, CID[c])} }}\n" for c in CID)


imgs = [f"\t\tSOV_pres_leader_portrait = {{\n{portrait_list('SOV_pres_leader_char')}\t\t\t{BLANK} = yes\n\t\t}}\n"]
for L in LAYOUTS:
    for i in range(1, L[2] + 1):
        imgs.append(f"\t\tSOV_pres_L{L[0]}_s{i}_portrait = {{\n"
                    f"\t\t\t{BLANK} = {{ NOT = {{ AND = {{ {slot_shown(L, i)} }} }} }}\n"
                    f"{portrait_list(f'SOV_pres_seat_char^{i - 1}')}\t\t\t{UNKNOWN} = yes\n\t\t}}\n")
write("common/focus_inlay_windows/SOV_Stalin_presidium_inlay_window.txt", HDR + f"""SOV_Stalin_presidium_inlay = {{
	window_name = SOV_presidium_inlay_window
	internal = no
	visible = {{ has_country_flag = SOV_pres_initialized }}
	scripted_images = {{
{''.join(imgs)}	}}
}}
""")


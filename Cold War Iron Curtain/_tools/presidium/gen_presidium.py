E.append(f"\tset_variable = {{ SOV_pres_leader_char = {CID[START_LEADER[0]]} }} # {START_LEADER[0]}\n"
         f"\tset_variable = {{ SOV_pres_leader_title = {MID[START_LEADER[1]]} }} # {START_LEADER[1]}\n"
         "\tclear_array = SOV_pres_seat_min\n\tclear_array = SOV_pres_seat_char\n")
for m, h in START_SEATS:
    E.append(f"\tadd_to_array = {{ SOV_pres_seat_min = {MID[m]} }} add_to_array = {{ SOV_pres_seat_char = {CID[h] if h else 0} }} # {m}: {h or 'vacant'}\n")

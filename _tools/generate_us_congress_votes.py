def generate_triggers(bills):
    lines = [HEADER.rstrip()]
    for bill in bills:
        lines.extend([
            unlocked(bill) + " = {",
            f'    {bill["unlock"]}',
            f'    NOT = {{ is_in_array = {{ array = usa_introduced_congress_bills value = token:{bill["key"]} }} }}',
            "}",
        ])
    return "\n".join(lines) + "\n"



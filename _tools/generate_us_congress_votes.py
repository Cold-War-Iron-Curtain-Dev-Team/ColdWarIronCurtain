def localisation_index():
    index = {}
    for path in sorted((ROOT / "localisation/english").glob("*.yml")):
        if path == LOCALISATION:
            continue
        for m in re.finditer(r'^\s*([^\s:#]+):\d*\s*"(.*)"\s*$', path.read_text(encoding="utf-8-sig"), re.M):
            index[m[1]] = m[2]
    return index


def bill_metadata():
    loc = localisation_index()
    records = json.loads(CATALOGUE.read_text(encoding="utf-8"))
    fields = {
        "unlock", "icon", "bipartisan", "support", "start", "preview", "house",
        "senate", "pass_notice", "pass", "fail", "after_vote",
    }
    bills = []
    for key, record in records.items():
        assert not set(record) - fields, (key, set(record) - fields)
        title = loc[key]
        for _ in range(10):
            expanded = re.sub(r'\$([^$]+)\$', lambda m: loc.get(m[1], m[1]), title)
            if expanded == title:
                break
            title = expanded
        title = re.sub("\u00a7.", "", title).replace("\\n", " ")
        assert "$" not in title and title != key, (key, title)
        short = title.removeprefix("The ")
        if len(short) > 44:
            short = short[:41].rsplit(" ", 1)[0] + "..."
        bills.append({
            "key": key, "title": title, "short": short, "short_key": f"USA_CONGRESS_SHORT_{key}",
            "house": 217, "senate": None, "bipartisan": "0.55", **record,
        })
    return bills


def unlocked(bill):
    return f'USA_congress_unlocked_{bill["key"]}'


def switch(name, bills, body, *, selector="usa_current_legislation"):
    lines = [name + " = {"]
    for index, bill in enumerate(bills):
        branch = "if" if index == 0 else "else_if"
        lines.extend([
            f"    {branch} = {{",
            f'        limit = {{ check_variable = {{ {selector} = token:{bill["key"]} }} }}',
            *("        " + effect for effect in body(bill)),
            "    }",
        ])
    lines.append("}")
    return "\n".join(lines)


def generate_decisions(bills):
    lines = [HEADER + "CONGRESS_US = {"]
    for bill in bills:
        key = bill["key"]
        lines.append(f"    {key} = {{")
        if "icon" in bill:
            lines.append(f'        icon = {bill["icon"]}')
        lines.extend([
            "        allowed = { tag = USA }",
            "        visible = {",
            "            OR = { is_ai = yes has_country_flag = usa_introducing_bill_from_overview }",
            "            " + unlocked(bill) + " = yes",
            "        }",
            "        available = { USA_can_start_congress_vote = yes }",
            "        ai_will_do = { factor = 10 }",
            "        cost = 0",
            "        fire_only_once = yes",
            f"        days_remove = {BILL_VOTE_DAYS}",
            "        complete_effect = {",
            "            hidden_effect = {",
            f"                set_temp_variable = {{ usa_starting_congress_bill = token:{key} }}",
            "                USA_start_congress_vote = yes",
            "            }",
        ])
        preview = bill.get("preview", bill["pass"])
        if preview:
            lines.extend(["            effect_tooltip = {", *("                " + effect for effect in preview), "            }"])
        lines.extend([
            "        }",
            "        remove_effect = {",
            f"            set_temp_variable = {{ usa_expiring_congress_bill = token:{key} }}",
            "            USA_expire_congress_vote = yes",
            "        }",
            "    }",
        ])
    return "\n".join([*lines, "}"]) + "\n"


def configure(bill):
    return [
        f'set_temp_variable = {{ usa_bill_house = {bill["house"]} }}',
        f'set_temp_variable = {{ usa_bill_senate = {bill["senate"] or 0} }}',
        f'set_temp_variable = {{ usa_bill_short = token:{bill["short_key"]} }}',
        f'set_temp_variable = {{ usa_bill_effects = token:USA_CONGRESS_EFFECTS_{bill["key"]} }}',
    ]


def generate_vote_clock():
    lines = [
        "USA_set_congress_vote_duration = {",
        f"    set_temp_variable = {{ usa_vote_duration = {BILL_VOTE_DAYS} }}",
        "    if = {",
        "        limit = { check_variable = { usa_current_legislation = token:McCarran_Walter_Act_Override } }",
        "        set_temp_variable = { usa_vote_duration = 40 }",
        "    }",
        "}",
        "",
        "# The law_passing flag already records the start day in older saves.",
        "USA_recover_congress_vote_age = {",
        f"    set_temp_variable = {{ usa_vote_age = {BILL_VOTE_DAYS} }}",
    ]
    for age in range(BILL_VOTE_DAYS):
        branch = "if" if age == 0 else "else_if"
        lines.append(f"    {branch} = {{ limit = {{ has_country_flag = {{ flag = law_passing days < {age + 1} }} }} set_temp_variable = {{ usa_vote_age = {age} }} }}")
    lines.append("}")
    return "\n".join(lines)


def setup(bill):
    return [
        f'set_variable = {{ bipartisan_value = {bill["bipartisan"]} }}',
        "bipartisan_house_calc = yes",
        *(f"senate_{group}_support = yes" for group in bill["support"]),
        *bill.get("start", []),
    ]


def passed(bill):
    notice = ["country_event = { id = us_congress.100 }"] if bill.get("pass_notice", True) else []
    return [*notice, *bill["pass"]]


def generate_activation(bills):
    lines = [
        "USA_activate_congress_bill = {",
        "    set_temp_variable = { usa_native_bill_started = 0 }",
        "    set_country_flag = usa_introducing_bill_from_overview",
    ]
    for index, bill in enumerate(bills):
        branch = "if" if index == 0 else "else_if"
        key = bill["key"]
        lines.extend([
            f"    {branch} = {{",
            f"        limit = {{ check_variable = {{ usa_selected_congress_bill = token:{key} }} {unlocked(bill)} = yes }}",
            f"        activate_decision = {key}",
            f"        if = {{ limit = {{ has_decision = {key} }} set_temp_variable = {{ usa_native_bill_started = 1 }} }}",
            "    }",
        ])
    lines.extend([
        "    clr_country_flag = usa_introducing_bill_from_overview",
        "    if = {",
        "        limit = { check_variable = { usa_native_bill_started = 1 } }",
        "        set_temp_variable = { usa_starting_congress_bill = usa_selected_congress_bill }",
        "        USA_start_congress_vote = yes",
        "    }",
        "}",
    ])
    return "\n".join(lines)


def generate_effects(bills):
    lines = [
        HEADER.rstrip(),
        switch("USA_configure_congress_vote", bills, configure, selector="usa_bill_key"),
        generate_vote_clock(),
        switch("USA_apply_congress_start_effects", bills, setup),
        switch("USA_apply_congress_pass_effects", bills, passed),
        switch("USA_apply_congress_failure_override", [b for b in bills if "fail" in b],
               lambda b: ["set_temp_variable = { usa_custom_congress_failure = 1 }", *b["fail"]]),
        switch("USA_apply_congress_after_vote", [b for b in bills if "after_vote" in b], lambda b: b["after_vote"]),
        generate_activation(bills),
        "USA_collect_congress_bills = {",
        "    clear_array = usa_available_congress_bills",
    ]
    for bill in bills:
        lines.append(f'    if = {{ limit = {{ {unlocked(bill)} = yes }} add_to_array = {{ usa_available_congress_bills = token:{bill["key"]} }} }}')
    lines.extend(["}", "", "USA_find_legacy_congress_bill = {"])
    # Only the bills omitted from the former overview can have a native timer
    # without a bill token. The current decision ID is stable across saves.
    legacy_bills = [bill for bill in bills if bill["key"] in LEGACY_WITHOUT_TOKEN]
    legacy_bills.sort(key=lambda bill: bill["key"] == "Metric_Conversion_Act")
    for index, bill in enumerate(legacy_bills):
        branch = "if" if index == 0 else "else_if"
        key = bill["key"]
        lines.append(f"    {branch} = {{ limit = {{ has_decision = {key} }} set_variable = {{ usa_current_legislation = token:{key} }} }}")
    lines.append("}")
    return "\n".join(lines) + "\n"



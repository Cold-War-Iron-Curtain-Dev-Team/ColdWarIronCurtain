def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    bills = bill_metadata()
    scripted_loc, localisation = generate_localisation(bills)
    tokens = {"McCarran_Walter_Act_Override", "USA_CONGRESS_SHORT_MCCARRAN_OVERRIDE",
              "USA_CONGRESS_EFFECTS_MCCARRAN_OVERRIDE"}
    for bill in bills:
        tokens.update((bill["key"], bill["short_key"], f'USA_CONGRESS_EFFECTS_{bill["key"]}'))
    # Keep existing token order when adding new bills to the registry.
    existing = [
        line for line in TOKENS.read_text(encoding="utf-8").splitlines()
        if line and not line.startswith("#")
    ] if TOKENS.exists() else []
    registered = existing + sorted(tokens - set(existing))
    outputs = (
        (DECISIONS, generate_decisions(bills)),
        (EFFECTS, generate_effects(bills)),
        (TRIGGERS, generate_triggers(bills)),
        (TOKENS, HEADER + "\n".join(registered) + "\n"),
        (SCRIPTED_LOC, scripted_loc),
        (LOCALISATION, localisation),
    )
    for path, content in outputs:
        encoding = "utf-8-sig" if path == LOCALISATION else "utf-8"
        if args.check:
            assert path.read_text(encoding=encoding) == content, f"Regenerate {path.name}"
        else:
            path.write_text(content, encoding=encoding, newline="\n")
    print(f"PASS: {len(bills)} native votes generated from the Congress bill catalogue.")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Writes the 1949 GDP targets (MODEL.md 0.1 hybrid anchor) into the mod as scripted effects.

The start factor is calibrated in game: cwic_set_start_productivity runs the GDP pass with factor 1,
then sets cwic_start_productivity = target / raw GDP, so each country's 1949 GDP lands on its target
whatever the differences between the simulator's and the game's inputs.

  python _tools/economy_check/sim/gen_start_productivity.py
"""
import csv, os

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.abspath(os.path.join(HERE, '..', '..', '..', 'Cold War Iron Curtain'))
SRC = os.path.join(HERE, 'out', 'start_productivity.csv')
DST = os.path.join(MOD, 'common', 'scripted_effects', 'CWIC_Start_Productivity_Generated.txt')

rows = sorted((r for r in csv.DictReader(open(SRC)) if r['target_gdp'].strip()), key=lambda r: r['tag'])
out = ['# Generated by _tools/economy_check/sim/gen_start_productivity.py. Do not edit by hand.',
       'cwic_set_target_gdp_1949 = {',
       '\tset_variable = { cwic_target_gdp_1949 = 0 }']
for r in rows:
    out.append('\tif = { limit = { original_tag = %s } set_variable = { cwic_target_gdp_1949 = %.3f } }'
               % (r['tag'], float(r['target_gdp'])))
out += ['}',
        'cwic_set_start_productivity = {',
        '\tset_variable = { cwic_target_gdp_1949 = 0 }',
        '\tif = { limit = { date < 1949.7.1 } cwic_set_target_gdp_1949 = yes }',
        '\tset_variable = { cwic_start_productivity = 1 }',
        '\tif = { limit = { check_variable = { global.cwic_start_prod_raw > 0 } } set_variable = { cwic_start_productivity = global.cwic_start_prod_target } divide_variable = { cwic_start_productivity = global.cwic_start_prod_raw } }',
        '\tif = {',
        '\t\tlimit = { check_variable = { cwic_target_gdp_1949 > 0 } }',
        '\t\tset_variable = { cwic_start_productivity = 1 }',
        '\t\tgdp_calculation_effect = yes',
        '\t\tif = {',
        '\t\t\tlimit = { check_variable = { grossdomesticproduct > 0.001 } }',
        '\t\t\tadd_to_variable = { global.cwic_start_prod_raw = grossdomesticproduct }',
        '\t\t\tadd_to_variable = { global.cwic_start_prod_target = cwic_target_gdp_1949 }',
        '\t\t\tset_variable = { cwic_start_productivity = cwic_target_gdp_1949 }',
        '\t\t\tdivide_variable = { cwic_start_productivity = grossdomesticproduct }',
        '\t\t\tclamp_variable = { var = cwic_start_productivity min = 0.001 max = 1000 }',
        '\t\t}',
        '\t}',
        '\telse_if = {',
        '\t\tlimit = { capital_scope = { has_variable = cwic_gdp_owner_month } }',
        '\t\tcapital_scope = { var:cwic_gdp_owner_month = { set_temp_variable = { cwic_inherited_prod = cwic_start_productivity } } }',
        '\t\tif = { limit = { check_variable = { cwic_inherited_prod > 0 } } set_variable = { cwic_start_productivity = cwic_inherited_prod } }',
        '\t}',
        '\tgdp_calculation_effect = yes',
        '}']
open(DST, 'w', newline='\n').write('\n'.join(out) + '\n')
print('%d countries -> %s' % (len(rows), os.path.relpath(DST, MOD)))

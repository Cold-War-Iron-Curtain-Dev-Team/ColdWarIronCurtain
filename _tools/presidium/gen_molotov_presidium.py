"""Generates the Molotov-era presidium inlay files from molotov_presidium_data.py.

Run:  python gen_molotov_presidium.py
Writes into the mod folder two levels up (this file lives in <repo>/_tools/presidium/,
next to the mod folder). Set MOD_ROOT to override.

Unlike the Stalin panel (gen_presidium.py), this panel is STATIC: it never
reads the shared SOV_pres_* seat array - no dead, dismissed or stale member
can ever leak into it. It is also REVEAL-GATED: only Molotov is drawn until
the focuses in REVEALS / DEFAULT_REVEAL (molotov_presidium_data.py) complete,
then each seat appears; hidden seats fall back to a fully blank sprite with
no tooltip at all. The revealing focuses carry SOV_mpres_reveal_*
custom_effect_tooltip lines in the tree (hand-added there); this generator
emits their loc text. SOV_pres_molotov_government (still generated below)
mirrors the full government into the shared state so other content can read
it. Layout math mirrors gen_presidium.py on purpose - keep them in sync.
"""
import os
import re
from pathlib import Path

from presidium_data import CHARACTERS, FACTIONS, MINISTRIES, TRAITS, UNKNOWN
from molotov_presidium_data import *  # noqa: F401,F403  (this panel's config)

MOD = Path(os.environ.get("MOD_ROOT") or (Path(__file__).resolve().parents[2] / "Cold War Iron Curtain"))
HDR = "# GENERATED by _tools/presidium/gen_molotov_presidium.py - edit molotov_presidium_data.py instead\n"
BLANK = "GFX_SOV_pres_blank"  # sprite emitted by gen_presidium.py

CID = {c["key"]: i + 1 for i, c in enumerate(CHARACTERS)}
FID = {f[0]: i + 1 for i, f in enumerate(FACTIONS)}
MID = {m[0]: i + 1 for i, m in enumerate(MINISTRIES)}
MIN = {m[0]: m for m in MINISTRIES}
CH = {c["key"]: c for c in CHARACTERS}
LEADER, LEADER_MIN = START_LEADER
CAST = [LEADER] + [h for _, h in START_SEATS]
COLS = max(ROW_PROFILE)

# ---- validation
for key in PORTRAITS:
    assert key in CID, f"PORTRAITS: unknown character {key}"
assert LEADER in CID and LEADER_MIN in MID, "bad START_LEADER"
assert LEADER in PORTRAITS, "the big leader portrait must exist"
for m, h in START_SEATS:
    assert m in MID and h in CID, f"START_SEATS: bad entry {m}, {h}"
assert len({h for _, h in START_SEATS}) == len(START_SEATS), "duplicate holder in START_SEATS"
assert len(START_SEATS) == sum(ROW_PROFILE), f"ROW_PROFILE {ROW_PROFILE} must hold all {len(START_SEATS)} seats"
assert all(1 <= r <= COLS for r in ROW_PROFILE), "a row is wider than COLS"
assert COLS >= 1
assert LEADER_SCALE > 0 and PORTRAIT_NATIVE[0] > 0 and PORTRAIT_NATIVE[1] > 0
assert 0 < UI_SCALE <= 2, "UI_SCALE must be in (0, 2]"
assert set(BIOS) == {LEADER} | {h for _, h in START_SEATS}, "BIOS must cover exactly the panel cast (leader + seat holders)"
for k in CAST:
    assert k in RANKS, f"RANKS: missing panel cast member {k}"
    assert k in RELATIONS, f"RELATIONS: missing panel cast member {k}"
for k in RELATIONS:
    assert k in CID, f"RELATIONS: unknown character {k}"
    assert -100 <= RELATIONS[k] <= 100, f"RELATIONS: {k} out of range"
for k in RANKS:
    assert k in CID and RANKS[k] in (0, 1, 2), f"RANKS: bad entry {k}"

# ---- reveal validation: focus ids must exist in the tree and have titles
SEAT_HOLDERS = {h for _, h in START_SEATS}
assert set(REVEALS) <= SEAT_HOLDERS, f"REVEALS: unknown seat holder {set(REVEALS) - SEAT_HOLDERS}"
assert LEADER not in REVEALS, "REVEALS: the leader has no seat to reveal"
REVEAL_IDS = list(REVEALS.values()) + [DEFAULT_REVEAL]
_tree = MOD / TREE_FILE
_tree_txt = _tree.read_bytes().decode("utf-8") if _tree.exists() else None
if _tree_txt is not None:
    for fid in REVEAL_IDS:
        assert re.search(rf"(?m)^\s*id = {re.escape(fid)}\s*$", _tree_txt), \
            f"reveal focus {fid} not found in {TREE_FILE}"
_lockeys = set()
if (MOD / "localisation/english").exists():
    for yml in (MOD / "localisation/english").glob("*.yml"):
        _lockeys |= set(re.findall(r"(?m)^\s*(\S+?):\d", yml.read_bytes().decode("utf-8", errors="replace")))
    for fid in REVEAL_IDS:
        assert fid in _lockeys, f"reveal focus {fid} has no english loc title (vacant tooltips quote it)"


def write(rel, data, bom=False):
    p = MOD / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(data, encoding="utf-8-sig" if bom else "utf-8")
    print("wrote", rel)


# ============================================================ layout (same constants as gen_presidium.py)
W, TOP, GRID_H, TEXT_H = 1000, 45, 560, 54
LEFT_W = int(PORTRAIT_NATIVE[0] * LEADER_SCALE) + 40   # left column fits the big portrait
GRID_W = W - LEFT_W - 5
N_SEATS = len(START_SEATS)
ROWS = len(ROW_PROFILE)
CELL_W = GRID_W // COLS
assert CELL_W >= 130, f"seat cell too narrow: {CELL_W}"
SCALE = min(0.65, (GRID_H / ROWS - TEXT_H - 6) / PORTRAIT_NATIVE[1], (CELL_W - 10) / PORTRAIT_NATIVE[0])
ROW_H = int(PORTRAIT_NATIVE[1] * SCALE) + TEXT_H + 6
H = TOP + ROWS * ROW_H + 10
LEADER_W = int(PORTRAIT_NATIVE[0] * LEADER_SCALE)
LEADER_H = int(PORTRAIT_NATIVE[1] * LEADER_SCALE)
LEADER_X = (LEFT_W - LEADER_W) // 2
LEADER_NAME_Y = 60 + LEADER_H + 4


# The whole .gui is emitted at UI_SCALE so the panel can be sized against the
# zoomed-out focus view (fonts keep their native size - only geometry scales).
def sx(v):
    return int(round(v * UI_SCALE))


def seat_pos(i):
    """1-based seat number -> (icon_x, icon_y, text_y). Rows fill in the
    ROW_PROFILE order; rows narrower than COLS are centred in the grid."""
    r, rem = 0, i
    while rem > ROW_PROFILE[r]:
        rem -= ROW_PROFILE[r]
        r += 1
    row_n = ROW_PROFILE[r]
    cx = LEFT_W + (rem - 1) * CELL_W + ((COLS - row_n) * CELL_W) // 2
    cy = TOP + r * ROW_H
    return cx, cy, cy + int(PORTRAIT_NATIVE[1] * SCALE) + 2


def sprite_of(key):
    """Portrait sprite of a cast member, or the silhouette placeholder."""
    return PORTRAITS.get(key, UNKNOWN)


# ============================================================ .gui
def text(name, x, y, w, ctx, font="hoi_16mbs"):
    return f"""		instantTextBoxType = {{
			name = "{name}"
			position = {{ x = {x} y = {y} }}
			font = "{font}"
			context_aware_text = {ctx}
			maxWidth = {w}
			maxHeight = 18
			fixedsize = yes
			format = center
			alwaystransparent = yes
		}}
"""


def icon(name, x, y, sc, tt):
    return f"""		iconType = {{
			name = "{name}"
			spriteType = "{BLANK}"
			position = {{ x = {x} y = {y} }}
			scale = {sc:.2f}
			context_aware_tooltip = {tt}
		}}
"""


gui = [HDR, f"""guiTypes = {{
	containerWindowType = {{
		name = "{WINDOW_NAME}"
		position = {{ x = 0 y = 0 }}
		size = {{ width = {sx(W)} height = {sx(H)} }}
		clipping = no
		background = {{ name = "background" quadTextureSprite = "GFX_tiled_window_transparent" }}
"""]
gui.append(text(f"{PREFIX}_title", 0, sx(10), sx(W), f"[{PREFIX}_title_text]", "hoi_20bs"))
gui.append(icon(f"{PREFIX}_leader_portrait", sx(LEADER_X), sx(60), LEADER_SCALE * UI_SCALE, f"[{PREFIX}_leader_tt]"))
gui.append(text(f"{PREFIX}_leader_name", 0, sx(LEADER_NAME_Y), sx(LEFT_W), f"[{PREFIX}_leader_name]", "hoi_18mbs"))
gui.append(text(f"{PREFIX}_leader_title", 0, sx(LEADER_NAME_Y) + 20, sx(LEFT_W), f"[{PREFIX}_leader_title]"))
for i, (m, h) in enumerate(START_SEATS, 1):
    cx, cy, py = seat_pos(i)
    n = f"{PREFIX}_s{i}"
    ix = cx + (CELL_W - int(PORTRAIT_NATIVE[0] * SCALE)) // 2
    gui.append(icon(f"{n}_portrait", sx(ix), sx(cy), SCALE * UI_SCALE, f"[{n}_tt]"))
    # text line pitch (+16/+32) stays unscaled so the fixed-size fonts don't overlap
    gui.append(text(f"{n}_name", sx(cx), sx(py), sx(CELL_W - 4), f"[{n}_name]"))
    gui.append(text(f"{n}_title", sx(cx), sx(py) + 16, sx(CELL_W - 4), f"[{n}_title]"))
    gui.append(text(f"{n}_faction", sx(cx), sx(py) + 32, sx(CELL_W - 4), f"[{n}_faction]"))
gui.append("\t}\n}\n")
write(GUI_FILE, "".join(gui))

# ============================================================ inlay window (reveal-gated picks)
# Molotov is always drawn; each seat shows its portrait only once the focus
# that appoints its holder has completed, else the fully blank sprite
# (scripted_images picks are first-true-wins).
imgs = [f"\t\t{PREFIX}_leader_portrait = {{\n\t\t\t{sprite_of(LEADER)} = yes\n\t\t}}\n"]
for i, (m, h) in enumerate(START_SEATS, 1):
    fid = REVEALS.get(h, DEFAULT_REVEAL)
    imgs.append(f"\t\t{PREFIX}_s{i}_portrait = {{\n"
                f"\t\t\t{sprite_of(h)} = {{ has_completed_focus = {fid} }}\n"
                f"\t\t\t{BLANK} = yes\n"
                f"\t\t}}\n")
write(DEF_FILE, HDR + f"""{PANEL_ID} = {{
	window_name = {WINDOW_NAME}
	internal = no
	visible = {{ has_country_flag = SOV_pres_initialized }}
	scripted_images = {{
{''.join(imgs)}	}}
}}
""")

# ============================================================ scripted localisation (leader static, seats reveal-gated)
def fixed(name, key):
    return f"defined_text = {{\n\tname = {name}\n\ttext = {{ localization_key = {key} }}\n}}\n"


def gated(name, key, fid, fallback):
    """Revealed -> key, still hidden -> fallback (first-true-wins triggered text)."""
    return (f"defined_text = {{\n\tname = {name}\n"
            f"\ttext = {{ trigger = {{ has_completed_focus = {fid} }} localization_key = {key} }}\n"
            f"\ttext = {{ localization_key = {fallback} }}\n}}\n")


SL = [HDR]
SL.append(fixed(f"{PREFIX}_title_text", f"{PREFIX}_title"))
SL.append(fixed(f"{PREFIX}_leader_name", f"{PREFIX}_char_{LEADER}"))
SL.append(fixed(f"{PREFIX}_leader_title", f"{PREFIX}_min_{LEADER_MIN}"))
SL.append(fixed(f"{PREFIX}_leader_tt", f"{PREFIX}_char_{LEADER}_tt_leader"))
for i, (m, h) in enumerate(START_SEATS, 1):
    fid = REVEALS.get(h, DEFAULT_REVEAL)
    SL.append(gated(f"{PREFIX}_s{i}_name", f"{PREFIX}_char_{h}_ui", fid, f"{PREFIX}_empty"))
    SL.append(gated(f"{PREFIX}_s{i}_title", f"{PREFIX}_min_{m}", fid, f"{PREFIX}_empty"))
    SL.append(gated(f"{PREFIX}_s{i}_faction", f"{PREFIX}_char_{h}_faction", fid, f"{PREFIX}_empty"))
    # a hidden seat is fully silent: blank portrait, no name, no tooltip
    SL.append(gated(f"{PREFIX}_s{i}_tt", f"{PREFIX}_char_{h}_tt", fid, f"{PREFIX}_empty"))
write(SCRIPTED_LOC_FILE, "\n".join(SL))

# ============================================================ localisation (self-contained, panel cast only)
LEGEND = ("§YHow to read the panel§!\\nNames: §Ygold§! full member, white candidate member, §ggrey§! not a member of the Politburo.\\n"
          "Factions: " + ", ".join(n for _, n in FACTIONS) + ".\\nHover over a portrait for his faction, standing and traits.")
RANK_TEXT = {2: "§YFull member§!", 1: "Candidate member", 0: "§gNot a member§!"}


def rel_text(v):
    return f"§G+{v}§!" if v >= 0 else f"§R{v}§!"


used_mins = {m for m, _ in START_SEATS} | {LEADER_MIN}
Lc = ["l_english:\n"]
Lc.append(f' {PREFIX}_title:0 "Presidium of the Central Committee and Government"\n')
# reveal gating: hidden seats fall back to this empty key (renders nothing -
# no name, no post, no tooltip). The appointing focuses announce their member
# in the tree via custom_effect_tooltip; this loc file only supplies its text.
Lc.append(f' {PREFIX}_empty:0 ""\n')
for m2, h2 in START_SEATS:
    if h2 in REVEALS:
        Lc.append(f' {PREFIX}_reveal_{h2}:0 "§Y{CH[h2]["name"]}§! joins the Presidium as {MIN[m2][1]}"\n')
Lc.append(f' {PREFIX}_reveal_generic:0 "More ministers will be appointed to the government"\n')
Lc += [f' {PREFIX}_min_{m}:0 "{MIN[m][1]}"\n' for m, _ in MINISTRIES if m in used_mins]
for ck in CAST:
    c = CH[ck]
    rk = RANKS[ck]
    rel = RELATIONS[ck]
    colored = f"§Y{c['name']}§!" if rk == 2 else (c["name"] if rk == 1 else f"§g{c['name']}§!")
    fac = FACTIONS[FID[c["faction"]] - 1][1]
    Lc += [f' {PREFIX}_char_{ck}:0 "{c["name"]}"\n',
           f' {PREFIX}_char_{ck}_ui:0 "{colored}"\n',
           f' {PREFIX}_char_{ck}_faction:0 "{fac}"\n']
    head = (f"§Y{c['name']}§!\\n{BIOS[ck]}\\n\\nFaction: {fac}\\n"
            f"Politburo: {RANK_TEXT[rk]}\\nRelationship with the leader: {rel_text(rel)}")
    traits = "".join(f"\\n§Y{TRAITS[t][0]}§!: {TRAITS[t][1]}" for t in c["traits"])
    Lc.append(f' {PREFIX}_char_{ck}_tt:0 "{head}' + (f"\\n{traits}" if traits else "") + '"\n')
    if ck == LEADER:
        Lc.append(f' {PREFIX}_char_{ck}_tt_leader:0 "§Y{c["name"]}§!\\n{BIOS[ck]}\\n\\n' + LEGEND + '"\n')
write(LOC_FILE, "".join(Lc), bom=True)

# ============================================================ scripted effects
# HOI4 scripted effects take NO parameters: arguments are passed in temp variables.
E = [HDR, """# ---------------------------------------------------------------------------
# Molotov-era presidium. COMPANION to the generated
# SOV_Stalin_presidium_effects.txt, which stays the single source of the
# shared SOV_pres_* state - do not duplicate those effects here.
#
# The Molotov PANEL itself is static (see gen_molotov_presidium.py): it never
# reads this state - it draws START_LEADER + START_SEATS with each seat
# appearing once its appointing focus completes. This effect still mirrors the
# full government into the shared variables so other content (events, focuses,
# triggers) can use them.
#
#   SOV_pres_molotov_guard      - call any time; re-applies Molotov's
#                                 government when the SOV_Molotov tree is
#                                 active and the panel state is missing or
#                                 stale (wired to on_startup/on_monthly_SOV).
#   SOV_pres_molotov_government - re-seats the whole presidium with Molotov's
#                                 government. Call this from the event or
#                                 focus that hands over to the Molotov tree.
# ---------------------------------------------------------------------------

"""]
E.append("SOV_pres_molotov_government = {\n")
E.append("\tset_country_flag = SOV_pres_presidium_name\t# shared panel title reads \"Presidium...\", not \"Politburo...\"\n")
E.append(f"\tset_variable = {{ SOV_pres_leader_char = {CID[LEADER]} }} # {LEADER}\n"
         f"\tset_variable = {{ SOV_pres_leader_title = {MID[LEADER_MIN]} }} # {LEADER_MIN}\n")
E.append("\t# relations with the leader (flavour, shown in tooltips)\n")
E += [f"\tset_variable = {{ SOV_pres_{k}_relation = {v} }}\n" for k, v in RELATIONS.items()]
E.append("\t# Politburo standing\n")
E += [f"\tset_variable = {{ SOV_pres_{k}_rank = {v} }}\n" for k, v in RANKS.items()]
E.append("\tSOV_pres_clear_seats = yes\n")
for m, h in START_SEATS:
    E.append(f"\tadd_to_array = {{ SOV_pres_seat_min = {MID[m]} }} add_to_array = {{ SOV_pres_seat_char = {CID[h] if h else 0} }} # {m}: {h or 'vacant'}\n")
E.append("""}

SOV_pres_molotov_guard = {
	if = {
		limit = {
			has_focus_tree = SOV_Molotov
			OR = {
				NOT = { has_country_flag = SOV_pres_initialized }
				NOT = { has_country_flag = SOV_pres_molotov_gov }
				NOT = { check_variable = { SOV_pres_molotov_gov_ver = SOV_pres_data_version } }
			}
		}
		if = { limit = { NOT = { has_country_flag = SOV_pres_initialized } } SOV_pres_init = yes }
		SOV_pres_molotov_government = yes
		set_country_flag = SOV_pres_molotov_gov
		set_variable = { SOV_pres_molotov_gov_ver = SOV_pres_data_version }
	}
}
""")
write(EFFECTS_FILE, "".join(E))

# ============================================================ on_actions
write(ON_ACTIONS_FILE, HDR + f"""on_actions = {{
	on_startup = {{
		effect = {{
			SOV = {{ SOV_pres_molotov_guard = yes }}
		}}
	}}
	on_monthly_SOV = {{
		effect = {{
			SOV = {{ SOV_pres_molotov_guard = yes }}
		}}
	}}
}}
""")

# ============================================================ focus tree position
tree = MOD / TREE_FILE
if tree.exists():
    s = tree.read_bytes().decode("utf-8")
    pat = r"(id = " + PANEL_ID + r"\s*\r?\n\s*position = \{ x = )\d+( y = )\d+"
    repl = r"\g<1>" + str(INLAY_POSITION[0]) + r"\g<2>" + str(INLAY_POSITION[1])
    s2 = re.sub(pat, repl, s)
    if s2 != s:
        tree.write_bytes(s2.encode("utf-8"))
        print("updated inlay position in", TREE_FILE)

print(f"reveal-gated display: {len(REVEALS)} seats unlock via their focus, "
      f"{N_SEATS - len(REVEALS)} via {DEFAULT_REVEAL}")
print(f"static panel: {LEADER} as {LEADER_MIN} + {N_SEATS} seats in rows {ROW_PROFILE} "
      f"(emitted at UI_SCALE {UI_SCALE}: seats x{SCALE * UI_SCALE:.2f}, leader x{LEADER_SCALE * UI_SCALE:.2f})")
print(f"panel {sx(W)}x{sx(H)} gui pixels at {INLAY_POSITION} in {TREE_FILE}")

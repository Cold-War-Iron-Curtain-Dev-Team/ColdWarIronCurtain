def defined_text(name, entries, default=None):
    out = [f"defined_text = {{\n\tname = {name}\n"]
    for trigger, key in entries:
        out.append(f"\ttext = {{\n\t\ttrigger = {{ {trigger} }}\n\t\tlocalization_key = {key}\n\t}}\n")
    if default:
        out.append(f"\ttext = {{\n\t\tlocalization_key = {default}\n\t}}\n")
    out.append("}\n")
    return "".join(out)



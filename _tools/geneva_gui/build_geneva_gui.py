def noise(size, seed, lo=0, hi=255):
    """Deterministic grain, so rebuilt art is byte-identical and --check can compare it."""
    rng = random.Random(seed)
    return Image.frombytes("L", size, bytes(rng.randint(lo, hi) for _ in range(size[0] * size[1])))


def hash_seed(text):
    return sum((i + 1) * ord(ch) for i, ch in enumerate(text))


def stamp(text, size, colour, angle=0, double=False, fsize=13):
    w, h = size
    pad = 16
    im = Image.new("RGBA", (w + pad * 2, h + pad * 2), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    box = (pad, pad, pad + w - 1, pad + h - 1)
    d.rectangle(box, outline=colour + (230,), width=2)
    if double:
        d.rectangle((box[0] + 4, box[1] + 4, box[2] - 4, box[3] - 4), outline=colour + (200,), width=1)
    text_centre(d, box, text, font(MONO_B, fsize), colour + (235,))
    if angle:
        im = im.rotate(angle, resample=Image.BICUBIC, expand=False)
    # roughen the ink like a rubber stamp
    grain = noise(im.size, hash_seed(text)).point(lambda v: 255 if v > 50 else 110)
    alpha = ImageChops.multiply(im.getchannel("A"), grain)
    im.putalpha(alpha)
    return im.crop((pad // 2, pad // 2, w + pad + pad // 2, h + pad + pad // 2)) if angle else im.crop((pad, pad, pad + w, pad + h))


def parchment(size, seed=3):
    w, h = size
    base = Image.new("RGB", size, PAPER)
    grad = Image.linear_gradient("L").resize(size)
    dark = Image.new("RGB", size, PAPER2)
    base = Image.composite(dark, base, grad)
    grain = noise(size, seed, 215, 255).convert("RGB")
    base = ImageChops.multiply(base, grain)
    return base.convert("RGBA")


# ================================================================ art
class Art:
    def __init__(self):
        self.files = {}     # relative path -> bytes
        self.sprites = []   # (name, rel path, frames, button)

    def add(self, name, im, frames=1, button=False):
        rel = f"{ART_DIR}/{name}.dds"
        buf = io.BytesIO()
        im = im.convert("RGBA")
        if not name.startswith(COLOUR_SPRITES):
            alpha = im.getchannel("A")
            im = ImageOps.grayscale(im.convert("RGB")).convert("RGBA")
            im.putalpha(alpha)
        if im.width % 4 == 0 and im.height % 4 == 0 and im.width * im.height >= 4096:
            im.save(buf, format="DDS", pixel_format="DXT5")
        else:
            im.save(buf, format="DDS")
        self.files[rel] = buf.getvalue()
        self.sprites.append((f"GFX_geneva_{name}", rel, frames, button))
        return im.size



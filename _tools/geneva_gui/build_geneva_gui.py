def option_long_names():
    """Full option names from the hand-written loc: tooltips can't nest a loc key."""
    text = (MOD / "localisation/english/CWIC_Geneva_Conference_l_english.yml").read_text(encoding="utf-8-sig")
    names = {}
    for line in text.splitlines():
        if line.startswith("GENEVA_CONF_C") and "_OPT_" in line:
            key, value = line.split(":", 1)
            c, o = key[len("GENEVA_CONF_C"):].split("_OPT_")
            names.setdefault(int(c), {})[int(o)] = value.strip().strip('"')
    return [[names[c][o] for o in range(OPTIONS[c])] for c in range(7)]



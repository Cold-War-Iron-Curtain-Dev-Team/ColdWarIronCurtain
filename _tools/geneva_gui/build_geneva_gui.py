def gfx_text(art):
    out = [GENERATED, "spriteTypes = {\n"]
    for name, rel, frames, button in art.sprites:
        out.append(f"\tspriteType = {{\n\t\tname = \"{name}\"\n\t\ttexturefile = \"{rel}\"\n")
        if frames > 1:
            out.append(f"\t\tnoOfFrames = {frames}\n")
        if button:
            out.append("\t\teffectFile = \"gfx/FX/buttonstate.lua\"\n")
        out.append("\t}\n")
    out.append("}\n")
    return "".join(out)


class Gui:
    def __init__(self):
        self.lines = []
        self.depth = 1

    def emit(self, s):
        self.lines.append("\t" * self.depth + s)

    def icon(self, name, sprite, x, y, frame=None):
        self.emit("iconType = {")
        self.depth += 1
        self.emit(f"name = \"{name}\"")
        self.emit(f"spriteType = \"GFX_geneva_{sprite}\"")
        self.emit(f"position = {{ x = {x} y = {y} }}")
        if frame:
            self.emit(f"frame = {frame}")
        self.depth -= 1
        self.emit("}")

    def text(self, name, key, x, y, w, h=20, fnt="Main_14", fmt="left", fixed=True):
        self.emit("instantTextboxType = {")
        self.depth += 1
        self.emit(f"name = \"{name}\"")
        self.emit(f"position = {{ x = {x} y = {y} }}")
        self.emit(f"font = \"{fnt}\"")
        self.emit(f"text = \"{key}\"")
        self.emit(f"maxWidth = {w}")
        self.emit(f"maxHeight = {h}")
        self.emit(f"format = {fmt}")
        if fixed:
            self.emit("fixedsize = yes")
        self.emit("textureFile = \"\"")
        self.emit("borderSize = { x = 0 y = 0 }")
        self.depth -= 1
        self.emit("}")

    def button(self, name, sprite, x, y, tooltip=None, text=None, fnt="Main_14_black", sound="click_default", shortcut=None):
        self.emit("buttonType = {")
        self.depth += 1
        self.emit(f"name = \"{name}\"")
        self.emit(f"spriteType = \"GFX_geneva_{sprite}\"")
        self.emit(f"position = {{ x = {x} y = {y} }}")
        if text:
            self.emit(f"buttonText = \"{text}\"")
            self.emit(f"buttonFont = \"{fnt}\"")
        if tooltip:
            self.emit(f"pdx_tooltip = \"{tooltip}\"")
        if shortcut:
            self.emit(f"shortcut = \"{shortcut}\"")
        self.emit(f"clicksound = {sound}")
        self.depth -= 1
        self.emit("}")

    def open(self, kind, name, x, y, w, h, extra=()):
        self.emit(f"{kind} = {{")
        self.depth += 1
        self.emit(f"name = \"{name}\"")
        self.emit(f"position = {{ x = {x} y = {y} }}")
        self.emit(f"size = {{ width = {w} height = {h} }}")
        for e in extra:
            self.emit(e)

    def close(self):
        self.depth -= 1
        self.emit("}")


class Sgui:
    """Collects scripted GUI triggers, effects and properties."""

    def __init__(self):
        self.triggers = []
        self.effects = []
        self.properties = []

    def visible(self, element, body):
        self.triggers.append((f"{element}_visible", body))

    def enabled(self, element, body):
        self.triggers.append((f"{element}_click_enabled", body))

    def click(self, element, body):
        self.effects.append((f"{element}_click", body))


